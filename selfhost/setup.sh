#!/usr/bin/env bash
# One-time setup for a new deployment. Run after ./build.sh.
#
#   ./setup.sh --domain example.com --app-name "My Messenger"
#
# Generates every key and secret (into ./secrets, which must NEVER be committed or lost) and writes ./.env.
# Re-running is safe: existing keys are never replaced, because replacing them would break every account and
# every app build.
set -euo pipefail
cd "$(dirname "$0")"

domain=""
app_name=""
while [ $# -gt 0 ]; do
  case "$1" in
    --domain) domain=$2; shift 2 ;;
    --app-name) app_name=$2; shift 2 ;;
    *) echo "unknown option $1" >&2; exit 2 ;;
  esac
done

mkdir -p secrets/registration
chmod 700 secrets   # only you (and root) can enter; files inside are readable by the containers' users

# 1. Server keys: zero-knowledge params, sealed-sender certificate, shared secrets
if [ ! -f secrets/secrets.yml ]; then
  docker run --rm --user "$(id -u):$(id -g)" -v "$PWD/secrets:/out" selfhost/chat-server:latest generate-secrets /out
else
  echo "secrets/secrets.yml exists; keeping existing keys"
fi
chmod 644 secrets/secrets.yml secrets/public.yml secrets/selfhost.env

# 2. TLS certificate for the internal registration-service connection
if [ ! -f secrets/registration/registration-cert.pem ]; then
  openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes -days 3650 \
    -subj "/CN=registration" -addext "subjectAltName=DNS:registration" \
    -keyout secrets/registration/registration-key.pem -out secrets/registration/registration-cert.pem 2>/dev/null
fi
chmod 644 secrets/registration/*.pem

# shellcheck disable=SC1091
. secrets/selfhost.env

# 3. Object storage credentials: the server gets full access; anyone may read profile avatars in "cdn"
cat > secrets/s3.json <<EOF
{
  "identities": [
    {
      "name": "chat-server",
      "credentials": [{"accessKey": "${S3_ACCESS_KEY}", "secretKey": "${S3_SECRET_KEY}"}],
      "actions": ["Admin", "Read", "Write", "List", "Tagging"]
    },
    {"name": "anonymous", "actions": ["Read:cdn"]}
  ]
}
EOF
chmod 644 secrets/s3.json

# 4. .env for docker compose
if [ -f .env ]; then
  echo ".env exists; not overwriting (delete it to regenerate)"
else
  public_value() { grep "^$1:" secrets/public.yml | cut -d' ' -f2; }
  # One line with literal \n separators; server.yml wraps it in a double-quoted YAML string.
  registration_ca=$(awk 'BEGIN { ORS = "\\n" } { print }' secrets/registration/registration-cert.pem)

  cat > .env <<EOF
# ---- Your deployment (edit these) ----
# chat.DOMAIN and cdn.DOMAIN must resolve to this server
DOMAIN=${domain:-example.com}
APP_NAME=${app_name:-Messenger}
IOS_BUNDLE_ID=com.example.messenger

# ---- Phone verification ----
# log = print codes to the registration container's log (development only); twilio = real SMS
SMS_SENDER=log
# Codes are sent in the phone's language (Arabic or English); this is the fallback: ar or en
SMS_DEFAULT_LANGUAGE=ar
# Fixed-code numbers that never get an SMS, e.g. +15555550100=123456,+15555550101=654321
TEST_NUMBERS=
TWILIO_ACCOUNT_SID=
TWILIO_AUTH_TOKEN=
TWILIO_MESSAGING_SERVICE_SID=
TWILIO_FROM_NUMBER=

# ---- Generated by setup.sh: do not edit ----
FDB_CLUSTER_FILE_CONTENTS=selfhost:$(openssl rand -hex 8)@10.89.0.10:4500
GROUPS_ZK_SERVER_PUBLIC=$(public_value groupsZkConfig.serverPublic)
UNIDENTIFIED_DELIVERY_CERTIFICATE=$(public_value unidentifiedDelivery.certificate)
REGISTRATION_SHARED_SECRET=${REGISTRATION_SHARED_SECRET}
REGISTRATION_CA_CERT=${registration_ca}
EOF
  chmod 600 .env
  echo "Wrote .env"
fi

cat <<EOF

Setup complete.
  * BACK UP ./secrets and ./.env somewhere safe. Losing them means every user must re-register.
  * App builds need the values in secrets/public.yml (trust roots and public parameters).
  * Start:  docker compose up -d        (add --profile public for HTTPS via Caddy)
EOF
