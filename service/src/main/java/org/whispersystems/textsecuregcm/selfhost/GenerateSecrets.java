package org.whispersystems.textsecuregcm.selfhost;

import com.google.protobuf.ByteString;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;
import java.security.KeyPairGenerator;
import java.security.SecureRandom;
import java.security.spec.ECGenParameterSpec;
import java.util.Base64;
import java.util.HexFormat;
import org.signal.libsignal.protocol.ecc.ECKeyPair;
import org.signal.libsignal.zkgroup.GenericServerSecretParams;
import org.signal.libsignal.zkgroup.ServerSecretParams;
import org.whispersystems.textsecuregcm.entities.MessageProtos;

/**
 * Generates every key and secret a fresh self-hosted deployment needs.
 * <p>
 * Usage: {@code java -cp TextSecureServer.jar org.whispersystems.textsecuregcm.selfhost.GenerateSecrets <dir>}
 * <p>
 * Writes three files into {@code <dir>} (refusing to overwrite them, since replacing these keys breaks every existing
 * account and every app build):
 * <ul>
 *   <li>{@code secrets.yml}: the server's secrets bundle (mode 600). <b>Back this up; never commit it.</b></li>
 *   <li>{@code public.yml}: public values for the server config <em>and</em> for building the apps (trust roots,
 *   zero-knowledge public parameters).</li>
 *   <li>{@code selfhost.env}: shared credentials for docker compose (S3 keys, registration-service secret).</li>
 * </ul>
 * Third-party credentials (Firebase, APNs, Google Play, App Store) are filled with throwaway keys that let the server
 * start; replace them with real ones before shipping apps.
 */
public class GenerateSecrets {

  private static final SecureRandom RANDOM = new SecureRandom();

  /** Arbitrary, but must not be one of libsignal's reserved test IDs (see CertificateCommand). */
  private static final int SEALED_SENDER_CERTIFICATE_ID = 1;

  public static void main(final String[] args) throws Exception {
    if (args.length != 1) {
      System.err.println("usage: GenerateSecrets <output directory>");
      System.exit(2);
    }

    final Path dir = Path.of(args[0]);
    Files.createDirectories(dir);
    for (final String name : new String[]{"secrets.yml", "public.yml", "selfhost.env"}) {
      if (Files.exists(dir.resolve(name))) {
        System.err.println(dir.resolve(name) + " already exists; refusing to overwrite keys.");
        System.exit(1);
      }
    }

    // Group credentials (zkgroup)
    final ServerSecretParams groups = ServerSecretParams.generate();
    // Call links (two generations kept by upstream) and chat/backup credentials
    final GenericServerSecretParams callingPreV101 = GenericServerSecretParams.generate();
    final GenericServerSecretParams calling = GenericServerSecretParams.generate();
    final GenericServerSecretParams chat = GenericServerSecretParams.generate();

    // Sealed sender: a long-lived trust root (embedded in apps) signs a server certificate
    final ECKeyPair sealedSenderRoot = ECKeyPair.generate();
    final ECKeyPair sealedSenderServer = ECKeyPair.generate();
    final byte[] certificate = MessageProtos.ServerCertificate.Certificate.newBuilder()
        .setId(SEALED_SENDER_CERTIFICATE_ID)
        .setKey(ByteString.copyFrom(sealedSenderServer.getPublicKey().serialize()))
        .build()
        .toByteArray();
    final byte[] signedCertificate = MessageProtos.ServerCertificate.newBuilder()
        .setCertificate(ByteString.copyFrom(certificate))
        .setSignature(ByteString.copyFrom(sealedSenderRoot.getPrivateKey().calculateSignature(certificate)))
        .build()
        .toByteArray();

    final String s3AccessKey = "selfhost" + HexFormat.of().formatHex(bytes(8));
    final String s3SecretKey = base64Url(bytes(30));
    final String registrationSharedSecret = HexFormat.of().formatHex(bytes(32));

    final String secrets = String.join("\n",
        "# Generated by GenerateSecrets. KEEP PRIVATE AND BACKED UP. Losing or changing these breaks all accounts.",
        "",
        "aws.accessKeyId: " + s3AccessKey,
        "aws.secretAccessKey: " + s3SecretKey,
        "cdn.accessKey: " + s3AccessKey,
        "cdn.accessSecret: " + s3SecretKey,
        "",
        "zkConfig-libsignal-0.42.serverSecret: " + b64(groups.serialize()),
        "callingZkConfigPreV101.serverSecret: " + b64(callingPreV101.serialize()),
        "callingZkConfigV101.serverSecret: " + b64(calling.serialize()),
        "chatZkConfig.serverSecret: " + b64(chat.serialize()),
        "unidentifiedDelivery.privateKey: " + b64(sealedSenderServer.getPrivateKey().serialize()),
        "",
        "registrationService.sharedSecret: " + registrationSharedSecret,
        "registrationService.collationKeySalt: " + b64(bytes(32)),
        "linkDevice.secret: " + b64(bytes(32)),
        "foundationDbMessages.versionstampCipherKey.0: " + b64(bytes(32)),
        "registrationWebAuthn.userHandleBlindingSecret: " + b64(bytes(32)),
        "currentReportingKey.secret: " + b64(bytes(32)),
        "currentReportingKey.salt: " + b64(bytes(16)),
        "",
        "# Shared with services this deployment does not run yet (contact discovery, PIN backup, storage, payments,",
        "# attachments v3). Random values keep them inert; set real ones when you add those services.",
        "directoryV2.client.userAuthenticationTokenSharedSecret: " + b64(bytes(32)),
        "directoryV2.client.userIdTokenSharedSecret: " + b64(bytes(32)),
        "svr2.userAuthenticationTokenSharedSecret: " + b64(bytes(32)),
        "svr2.userIdTokenSharedSecret: " + b64(bytes(32)),
        "svrb.userAuthenticationTokenSharedSecret: " + b64(bytes(32)),
        "svrb.userIdTokenSharedSecret: " + b64(bytes(32)),
        "storageService.userAuthenticationTokenSharedSecret: " + b64(bytes(32)),
        "paymentsService.userAuthenticationTokenSharedSecret: " + b64(bytes(32)),
        "tus.userAuthenticationTokenSharedSecret: " + b64(bytes(32)),
        "cdn3StorageManager.clientSecret: " + base64Url(bytes(24)),
        "gcpAttachments.rsaSigningKey: |",
        indent(pem("PRIVATE KEY", rsaPkcs8())),
        "",
        "# --- Third-party credentials: PLACEHOLDERS. Replace with your own before going live. ---",
        "# Firebase Cloud Messaging service-account JSON (Android push)",
        "fcm.credentials: |",
        indent(fakeServiceAccountJson()),
        "# Apple Push Notification service (iOS push): team ID, key ID and .p8 key from developer.apple.com",
        "apn.teamId: REPLACE_ME",
        "apn.keyId: REPLACE_ME",
        "apn.signingKey: |",
        indent(pem("PRIVATE KEY", ecPkcs8())),
        "googlePlayBilling.credentialsJson: |",
        indent(fakeServiceAccountJson()),
        "appleAppStore.encodedKey: |",
        indent(pem("PRIVATE KEY", ecPkcs8())),
        "keyTransparencyService.clientPrivateKey: |",
        indent(pem("PRIVATE KEY", ecPkcs8())),
        "",
        "# Unused features (donations, Cloudflare TURN, HLR lookup)",
        "stripe.apiKey: unset",
        "stripe.idempotencyKeyGenerator: " + b64(bytes(16)),
        "braintree.publicKey: unset",
        "braintree.privateKey: unset",
        "paymentsService.fixerApiKey: unset",
        "paymentsService.coinGeckoApiKey: unset",
        "turn.cloudflare.apiToken: unset",
        "hlrLookup.apiKey: unset",
        "hlrLookup.apiSecret: unset",
        "tlsKeyStore.password: unset",
        "");

    final String publicValues = String.join("\n",
        "# Generated by GenerateSecrets. Public values: safe to share, but must match secrets.yml.",
        "",
        "# --- Server config (selfhost/.env, written by setup.sh) ---",
        "groupsZkConfig.serverPublic: " + b64(groups.getPublicParams().serialize()),
        "unidentifiedDelivery.certificate: " + b64(signedCertificate),
        "",
        "# --- App builds (Android BuildConfig / iOS / Desktop config) ---",
        "# Sealed-sender trust root (Android: UNIDENTIFIED_SENDER_TRUST_ROOT)",
        "unidentifiedSenderTrustRoot: " + b64(sealedSenderRoot.getPublicKey().serialize()),
        "# Group credentials (Android: ZKGROUP_SERVER_PUBLIC_PARAMS)",
        "zkGroupServerPublicParams: " + b64(groups.getPublicParams().serialize()),
        "# Call links (Android: GENERIC_SERVER_PUBLIC_PARAMS)",
        "callLinkServerPublicParams: " + b64(calling.getPublicParams().serialize()),
        "# Chat/backup credentials (Android: BACKUP_SERVER_PUBLIC_PARAMS)",
        "backupServerPublicParams: " + b64(chat.getPublicParams().serialize()),
        "");

    final String env = String.join("\n",
        "# Generated by GenerateSecrets. Read by docker compose. KEEP PRIVATE.",
        "S3_ACCESS_KEY=" + s3AccessKey,
        "S3_SECRET_KEY=" + s3SecretKey,
        "REGISTRATION_SHARED_SECRET=" + registrationSharedSecret,
        "");

    writePrivate(dir.resolve("secrets.yml"), secrets);
    Files.writeString(dir.resolve("public.yml"), publicValues);
    writePrivate(dir.resolve("selfhost.env"), env);

    System.out.println("Wrote " + dir.resolve("secrets.yml") + ", " + dir.resolve("public.yml") + ", "
        + dir.resolve("selfhost.env"));
  }

  private static byte[] bytes(final int n) {
    final byte[] b = new byte[n];
    RANDOM.nextBytes(b);
    return b;
  }

  private static String b64(final byte[] b) {
    return Base64.getEncoder().encodeToString(b);
  }

  private static String base64Url(final byte[] b) {
    return Base64.getUrlEncoder().withoutPadding().encodeToString(b);
  }

  private static byte[] rsaPkcs8() throws Exception {
    final KeyPairGenerator generator = KeyPairGenerator.getInstance("RSA");
    generator.initialize(2048, RANDOM);
    return generator.generateKeyPair().getPrivate().getEncoded();
  }

  private static byte[] ecPkcs8() throws Exception {
    final KeyPairGenerator generator = KeyPairGenerator.getInstance("EC");
    generator.initialize(new ECGenParameterSpec("secp256r1"), RANDOM);
    return generator.generateKeyPair().getPrivate().getEncoded();
  }

  private static String pem(final String type, final byte[] der) {
    return "-----BEGIN " + type + "-----\n"
        + Base64.getMimeEncoder(64, "\n".getBytes()).encodeToString(der)
        + "\n-----END " + type + "-----";
  }

  /** A syntactically valid Google service-account JSON that authenticates nowhere. */
  private static String fakeServiceAccountJson() throws Exception {
    final String key = pem("PRIVATE KEY", rsaPkcs8()).replace("\n", "\\n");
    return "{ \"type\": \"service_account\", \"project_id\": \"replace-me\", \"client_id\": \"0\","
        + " \"client_email\": \"replace-me@replace-me.iam.gserviceaccount.com\", \"private_key_id\": \"replace-me\","
        + " \"private_key\": \"" + key + "\" }";
  }

  private static String indent(final String s) {
    return "  " + s.replace("\n", "\n  ");
  }

  private static void writePrivate(final Path path, final String content) throws IOException {
    Files.writeString(path, content);
    try {
      Files.setPosixFilePermissions(path, PosixFilePermissions.fromString("rw-------"));
    } catch (final UnsupportedOperationException ignored) {
      // non-POSIX filesystem
    }
  }
}
